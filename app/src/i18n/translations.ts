export type SupportedLanguage = 'en' | 'es' | 'ca' | 'va' | 'gl' | 'pt' | 'fr';

export const SUPPORTED_LANGUAGES: SupportedLanguage[] = ['en', 'es', 'ca', 'va', 'gl', 'pt', 'fr'];

// Valencian has no ISO 639-1 code of its own, so 'va' is ours. Anything
// formatted with Intl (dates, amounts) has to map it to Catalan's 'ca',
// whose month and day names are the Valencian ones too. Catalan ('ca')
// uses the same locale.
// Portuguese is the European one, so dates and amounts use pt-PT.
export function intlLocale(language: string): string {
  if (language === 'va' || language === 'ca') return 'ca-ES';
  if (language === 'pt') return 'pt-PT';
  return language;
}

