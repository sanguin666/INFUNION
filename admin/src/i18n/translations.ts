export const SUPPORTED_LANGUAGES: SupportedLanguage[] = ['en', 'es', 'va', 'gl', 'pt', 'fr'];

/**
 * Each language written in itself, never translated: somebody who opened
 * the dashboard in a language they cannot read has to recognise their own.
 */
export const LANGUAGE_NAMES: Record<SupportedLanguage, string> = {
  en: 'English',
  es: 'Español',
  va: 'Valencià',
  gl: 'Galego',
  pt: 'Português',
  fr: 'Français',
};

/**
 * The locale Intl formats dates with: Valencian has no code of its own and
 * uses Catalan's, and Portuguese is the European one.
 */
export function intlLocale(language: string): string {
  if (language === 'va') return 'ca-ES';
  if (language === 'pt') return 'pt-PT';
  return language;
}

