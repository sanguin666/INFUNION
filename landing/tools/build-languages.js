// Builds the landing's language pages (SEO, #per-language):
//   landing/index.html        Spanish (the root)
//   landing/<lang>/index.html English, French, Catalan, Valencian, Galician, Portuguese
// Each page has its text in the HTML itself, its own title and description,
// a canonical link, hreflang links to all seven versions, and JSON-LD.
// It also writes landing/sitemap.xml and landing/robots.txt.
//
// Source: landing/tools/template.html (the page layout) and the translations in
// landing/assets/i18n.js. After changing either, run from the repo root:
//   node landing/tools/build-languages.js
// Then commit the generated files with the change. No dependencies.

