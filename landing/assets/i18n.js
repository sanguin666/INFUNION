  var STORAGE_KEY = "ansae-landing-language";

  function applyLang(lang) {
    var t = TRANSLATIONS[lang] || TRANSLATIONS.es;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (t[key] !== undefined) el.textContent = t[key];
    });
    // Real app screenshots, taken in each language (assets/screens/<lang>/).
    document.querySelectorAll("[data-shot]").forEach(function (el) {
      el.src = "assets/screens/" + lang + "/" + el.getAttribute("data-shot") + ".webp?v=20261026-offer";
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-alt");
      if (t[key] !== undefined) el.alt = t[key];
    });
    document.querySelectorAll("[data-i18n-label]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-label");
      if (t[key] !== undefined) el.setAttribute("aria-label", t[key]);
    });
    document.querySelectorAll("[data-lang-select]").forEach(function (el) {
      el.value = lang;
    });
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      // Private browsing / blocked storage: language just won't persist.
    }
  }

  function initialLang() {
    var saved = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY);
    } catch (e) {
      // Ignore: fall back to the default below.
    }
    return TRANSLATIONS[saved] ? saved : "es";
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(initialLang());
    document.querySelectorAll("[data-lang-select]").forEach(function (el) {
      el.addEventListener("change", function () {
        applyLang(el.value);
      });
    });
  });
