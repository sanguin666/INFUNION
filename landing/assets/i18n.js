  var VARIANT = (function () {
    // Place pages (/religion/, /asociaciones/, ...) are built with their variant
    // already in data-for; the ?for= query keeps working on the home page.
    var attr = document.documentElement.getAttribute("data-for");
    if (attr && VARIANTS[attr]) return attr;
    var m = /[?&]for=([a-z]+)/.exec(window.location.search);
    return m && VARIANTS[m[1]] ? m[1] : null;
  })();

  // A module card shows on a variant when the module is offered to at least
  // one kind of place of that variant (same rule as the app, assets/modules.js).
  function showModuleCards() {
    var rules = window.INFUNION_MODULES;
    if (!rules) return;
    document.querySelectorAll("[data-module]").forEach(function (el) {
      var type = el.getAttribute("data-module");
      var only = rules.onlyFor[type];
      var show;
      if (VARIANT) {
        show = !only || rules.variants[VARIANT].some(function (place) {
          return only.indexOf(place) !== -1;
        });
      } else {
        show = rules.notOnGeneralPage.indexOf(type) === -1;
      }
      el.hidden = !show;
    });
  }

  var WORSHIP_SHOTS = ["home", "calendar", "donate", "requests", "admin", "admin-requests", "admin-home"];
  var STORAGE_KEY = "ansae-landing-language";

  function applyLang(lang) {
    var t = TRANSLATIONS[lang] || TRANSLATIONS.es;
    var over = VARIANT && VARIANTS[VARIANT][lang];
    if (over) {
      var merged = {};
      Object.keys(t).forEach(function (k) { merged[k] = t[k]; });
      Object.keys(over).forEach(function (k) { merged[k] = over[k]; });
      t = merged;
    }
    if (VARIANT) document.documentElement.setAttribute("data-for", VARIANT);
    showModuleCards();
    // Place pages (data-static-text) already have their own texts in the HTML.
    var staticText = document.documentElement.hasAttribute("data-static-text");
    if (!staticText) document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (t[key] !== undefined) el.textContent = t[key];
    });
    // Real app screenshots, taken in each language (assets/screens/<lang>/).
    document.querySelectorAll("[data-shot]").forEach(function (el) {
      var shot = el.getAttribute("data-shot");
      // The worship variant shows the Carmen demo (a church), the others the
      // Crecer Juntos association; shots without a worship copy stay shared.
      var folder = VARIANT === "worship" && WORSHIP_SHOTS.indexOf(shot) !== -1 ? "/worship/" : "/";
      el.src = "/assets/screens/" + lang + folder + shot + ".webp?v=20261110-shots";
    });
    if (!staticText) document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-alt");
      if (t[key] !== undefined) el.alt = t[key];
    });
    if (!staticText) document.querySelectorAll("[data-i18n-label]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-label");
      if (t[key] !== undefined) el.setAttribute("aria-label", t[key]);
    });
    document.querySelectorAll("[data-lang-select]").forEach(function (el) {
      el.value = lang;
    });
    document.documentElement.lang = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
      // Private browsing / blocked storage: language just won't persist.
    }
  }

  // Each language has its own address (/en/, /fr/, ... ; Spanish at /), and
  // the server-built HTML already has the text. The page's own language wins,
  // so every address stays in its language for search engines.
  function pageLang() {
    var lang = document.documentElement.lang;
    return TRANSLATIONS[lang] ? lang : "es";
  }

  function homeFor(lang) {
    return lang === "es" ? "/" : "/" + lang + "/";
  }

  document.addEventListener("DOMContentLoaded", function () {
    applyLang(pageLang());
    document.querySelectorAll("[data-lang-select]").forEach(function (el) {
      el.addEventListener("change", function () {
        // Go to that language's own page, keeping the audience and join hash.
        window.location.href = homeFor(el.value) + window.location.search + window.location.hash;
      });
    });
  });
